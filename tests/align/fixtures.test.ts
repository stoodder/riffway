import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { buildMidi, MIDI_SPECS } from '../fixtures/classtab-synthetic/midi-fixtures';
import { ASCII_DIR, CLASSTAB_DIR } from '../ascii/song-checks';

describe('synthetic fixtures (D2)', () => {
  it.each(Object.keys(MIDI_SPECS))('%s is generated by midi-fixtures.ts', (name) => {
    const committed = new Uint8Array(readFileSync(join(CLASSTAB_DIR, name)));
    expect(buildMidi(MIDI_SPECS[name])).toEqual(committed);
  });

  it('every MIDI in the folder has a generator spec', () => {
    const mids = readdirSync(CLASSTAB_DIR).filter((f) => f.endsWith('.mid'));
    expect(mids.sort()).toEqual(Object.keys(MIDI_SPECS).sort());
  });

  it('every fixture folder states that its files are authored by us', () => {
    for (const dir of [CLASSTAB_DIR, ASCII_DIR]) {
      const readme = join(dir, 'README.md');
      expect(existsSync(readme)).toBe(true);
      expect(readFileSync(readme, 'utf8')).toMatch(/authored by the Riffway authors|written by the Riffway authors/i);
    }
  });

  it('ClassTab-style tabs use CRLF line endings like the real corpus', () => {
    for (const f of readdirSync(CLASSTAB_DIR).filter((n) => n.endsWith('.txt'))) {
      const raw = readFileSync(join(CLASSTAB_DIR, f), 'latin1');
      expect(raw.split('\n').slice(0, -1).every((l) => l.endsWith('\r'))).toBe(true);
    }
  });
});
